for seat = 1, 4 do
    local slots, chip = CardOffsets[seat], ChipOffsets[seat][1][1].xy
    local d = slots[2][1] - slots[1][1]
    local side = norm(vec3(-d.y, d.x, 0.0)) * Config.Blackjack.SplitOffset
    if #(slots[1][1].xy + side.xy - chip) < #(slots[1][1].xy - side.xy - chip) then side = -side end
    CardOffsets[seat - 4] = {}
    for i, slot in ipairs(slots) do
        CardOffsets[seat - 4][i] = { slot[1] + side, slot[2] }
    end
end

